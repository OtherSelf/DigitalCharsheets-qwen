import { z } from 'zod';

/**
 * ─── LANDMARK: SHARED FIELD LIMITS ─────────────────────────────────────────
 * Пределы полей листа, общие для всех редакций. Числа намеренно щедрые:
 * homebrew-листы и старые данные не должны перестать сохраняться из-за
 * косметического ограничения. Контекстные диапазоны (характеристики 0–100,
 * деньги, раны) задаются в схемах редакций поверх этих базовых пределов.
 *
 * Зачем это вообще: `z.string()` без `max` пропускал мегабайтные заметки,
 * `z.number()` без `int()` — дробный опыт, а отрицательный капитал или
 * количество предметов доезжали до файла и ломали суммы на листе.
 */
export const FIELD_LIMITS = {
  /** id элемента массива/листа: машинный идентификатор, не текст. */
  id: 128,
  /** Имя персонажа, предмета, навыка, таланта. */
  name: 200,
  /** Короткая подпись: ранг, тип, диапазон, характеристика оружия. */
  short: 500,
  /** Обычная заметка к полю или элементу. */
  note: 10_000,
  /** Свободный текст: предыстория, заметки листа, описание. */
  long: 50_000,
  /** Максимум элементов в одном массиве листа. */
  array: 500,
  /** Деньги в целых единицах (троны/гельт/монеты). */
  money: 1_000_000_000,
  /** Опыт и потраченный опыт. */
  experience: 10_000_000,
  /** Текущие/максимальные раны, судьба, ресурсы. */
  pool: 9_999,
  /** Количество предметов. */
  quantity: 9_999,
  /** Вес: допускает дробные значения, но не бесконечность. */
  weight: 1_000_000,
  /** Характеристика d100. */
  stat: 100,
  /** Небольшой счётчик: AP, рейтинг, слоты. */
  small: 100,
} as const;

/** Строка-идентификатор: не пустая и не мегабайтная. */
export const idString = () => z.string().min(1).max(FIELD_LIMITS.id);

/** Короткая подпись с верхней границей. */
export const shortString = () => z.string().max(FIELD_LIMITS.short);

/** Заметка к полю/элементу. */
export const noteString = () => z.string().max(FIELD_LIMITS.note);

/** Дробное число в контекстном диапазоне. */
export const numberIn = (min: number, max: number) =>
  z.number().min(min).max(max);

/** Массив с ограничением количества элементов. */
export const listOf = <T extends z.ZodType>(
  item: T,
  max: number = FIELD_LIMITS.array,
) => z.array(item).max(max);
