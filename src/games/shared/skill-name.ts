/**
 * ─── LANDMARK: SKILL NAME PARTS ────────────────────────────────────────────
 * Разбор названия умения на «имя» и «характеристику в скобках».
 *
 * Бумажные листы DH пишут характеристику прямо в названии: `Акробатика
 * (Лов)`, `Учёное Знание (Инт)`. Новые строки хранят характеристику полем, а
 * у старых листов её приходится выводить из суффикса — и только для показа:
 * файл листа при чтении не переписывается.
 *
 * Скобки в названии не всегда характеристика: `Язык (Низкий Готик)`,
 * `Навигация (Наземная) (Инт)`. Поэтому суффиксом считается только короткое
 * «слово» без пробелов и вложенных скобок; всё остальное остаётся в имени.
 * Распознаёт ли это слово известный код характеристики, решает модуль
 * редакции: у dh2 набор кодов шире (есть `influence`).
 */

export interface SkillNameParts {
  /** Название без суффикса характеристики. */
  name: string;
  /** Текст в скобках в конце, если он похож на аббревиатуру; иначе null. */
  suffix: string | null;
}

/**
 * Суффикс: до шести букв/точки в круглых скобках в самом конце строки.
 * Пробел внутри скобок (`Низкий Готик`) — уже часть названия, не код.
 */
const TRAILING_SUFFIX = /^(.*?)\s*\(([^()]{1,6})\)$/u;
const ABBREVIATION_LIKE = /^[\p{L}\p{M}.]{1,6}$/u;

export function splitSkillName(raw: string): SkillNameParts {
  const trimmed = raw.trim();
  const match = trimmed.match(TRAILING_SUFFIX);
  if (!match) return { name: trimmed, suffix: null };

  const name = match[1].trim();
  const suffix = match[2].trim();
  if (!name || !ABBREVIATION_LIKE.test(suffix)) {
    return { name: trimmed, suffix: null };
  }
  return { name, suffix };
}
